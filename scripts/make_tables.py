"""Tables (eval/results/tables.md) and plots (eval/plots/) from raw run JSON."""

from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

RES = Path("eval/results")
T95 = {2: 12.706, 3: 4.303}
NAMES = {("tapegrad", True): "tapegrad (fused ops)",
         ("tapegrad", False): "tapegrad (composite ops)", ("torch", True): "PyTorch 2.x CPU"}


def ci(xs: list[float]) -> tuple[float, float]:
    mu = float(np.mean(xs))
    h = T95.get(len(xs), 2.0) * float(np.std(xs, ddof=1)) / math.sqrt(len(xs)) if len(xs) > 1 \
        else float("nan")
    return mu, h


def main() -> None:
    runs = [json.loads(p.read_text()) for p in sorted((RES / "train").glob("*.json"))]
    out = ["# Results (generated by scripts/make_tables.py)\n"]
    by = defaultdict(list)
    for r in runs:
        by[(r["impl"], r["fused"])].append(r)
    if runs:
        out += ["## Tiny Shakespeare, char-level GPT (818k params), 2,000 AdamW steps\n",
                "| implementation | final val loss | min val loss | steps/s (during run) | "
                "peak RSS MB | seeds |", "|---|---|---|---|---|---|"]
        for k, rs in by.items():
            fv = ci([r["val_loss"][-1][1] for r in rs])
            mv = ci([min(v for _, v in r["val_loss"]) for r in rs])
            sp = ci([r["steps_per_s"] for r in rs])
            mem = np.mean([r["peak_rss_mb"] for r in rs])
            out.append(f"| {NAMES[k]} | {fv[0]:.4f} ± {fv[1]:.4f} | {mv[0]:.4f} ± {mv[1]:.4f} | "
                       f"{sp[0]:.1f} ± {sp[1]:.1f} | {mem:.0f} | {len(rs)} |")
        # per-seed trajectory agreement vs torch
        out.append("\n### Trajectory agreement with PyTorch (same init, same batches, float32)\n")
        out.append("| seed | variant | max abs train-loss diff | step of max | "
                   "steps bit-identical | final val diff |")
        out.append("|---|---|---|---|---|---|")
        torch_by_seed = {r["seed"]: r for r in by[("torch", True)]}
        for k in (("tapegrad", True), ("tapegrad", False)):
            for r in sorted(by.get(k, []), key=lambda r: r["seed"]):
                t = torch_by_seed.get(r["seed"])
                if t is None:
                    continue
                d = np.abs(np.array(r["train_loss"]) - np.array(t["train_loss"]))
                out.append(f"| {r['seed']} | {NAMES[k]} | {d.max():.2e} | {int(d.argmax()) + 1} | "
                           f"{100 * float((d == 0).mean()):.1f}% | "
                           f"{abs(r['val_loss'][-1][1] - t['val_loss'][-1][1]):.2e} |")
                r["_diff"] = d
        out.append("")
        Path("eval/plots").mkdir(parents=True, exist_ok=True)
        fig, axes = plt.subplots(1, 2, figsize=(9, 3.4))
        colors = {("tapegrad", True): "#4C72B0", ("tapegrad", False): "#55A868",
                  ("torch", True): "#DD8452"}
        for k, rs in by.items():
            for r in rs:
                steps, vals = zip(*r["val_loss"], strict=True)
                axes[0].plot(steps, vals, color=colors[k], alpha=0.8,
                             label=NAMES[k] if r["seed"] == 0 else None,
                             linestyle="--" if k[0] == "torch" else "-")
                if "_diff" in r:
                    d = r["_diff"]
                    roll = np.array([d[max(0, i - 49) : i + 1].max() for i in range(len(d))])
                    axes[1].plot(roll, color=colors[k], alpha=0.7,
                                 label=NAMES[k] if r["seed"] == 0 else None)
        axes[0].set_xlabel("step")
        axes[0].set_ylabel("validation loss (nats/char)")
        axes[0].legend(frameon=False, fontsize=7)
        axes[1].set_xlabel("step")
        axes[1].set_ylabel("|train loss − PyTorch|, 50-step max")
        axes[1].ticklabel_format(axis="y", style="sci", scilimits=(0, 0))
        axes[1].legend(frameon=False, fontsize=7)
        for ax in axes:
            ax.spines[["top", "right"]].set_visible(False)
        fig.tight_layout()
        fig.savefig("eval/plots/training.png", dpi=150)
        plt.close(fig)
    bp = RES / "bench" / "bench.json"
    if bp.exists():
        b = json.loads(bp.read_text())
        out += ["## Speed (batch 32 x 64 tokens; median of 7 interleaved repeats of 60 steps)\n",
                "| implementation | BLAS threads | steps/s (median) | min-max | vs PyTorch |",
                "|---|---|---|---|---|"]
        torch_sp = {r["threads"]: r["mean"] for r in b["speed"] if r["impl"] == "torch"}
        for r in b["speed"]:
            out.append(f"| {NAMES[(r['impl'], r['fused'])]} | {r['threads']} | {r['mean']:.1f} | "
                       f"{min(r['steps_per_s']):.1f}-{max(r['steps_per_s']):.1f} | "
                       f"{r['mean'] / torch_sp[r['threads']]:.2f}x |")
        out += ["\n## Memory of one forward + backward (tracemalloc, tapegrad)\n",
                "| ops | tape freed during backward | tape after forward MB | peak MB |",
                "|---|---|---|---|"]
        for m in b["memory"]:
            out.append(f"| {'fused' if m['fused'] else 'composite'} | {m['free_tape']} | "
                       f"{m['tape_mb_after_forward']:.1f} | {m['peak_mb_forward_backward']:.1f} |")
        out.append("")
    (RES / "tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
